CREATE TABLE IF NOT EXISTS users (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
full_name TEXT NOT NULL,
email TEXT NOT NULL UNIQUE,
password_hash TEXT NOT NULL,
role TEXT NOT NULL DEFAULT 'user'
CHECK (role IN ('user', 'admin', 'owner')),
account_status TEXT NOT NULL DEFAULT 'active'
CHECK (account_status IN ('active', 'suspended', 'closed')),
email_verified SMALLINT NOT NULL DEFAULT 0
CHECK (email_verified IN (0, 1)),
created_at TEXT NOT NULL DEFAULT
(TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE IF NOT EXISTS email_verification_tokens (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
token_hash TEXT NOT NULL UNIQUE,
expires_at BIGINT NOT NULL,
used_at BIGINT,
created_at BIGINT NOT NULL DEFAULT
(FLOOR(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000)::BIGINT)
);

CREATE INDEX IF NOT EXISTS idx_verification_tokens_user
ON email_verification_tokens(user_id);

CREATE INDEX IF NOT EXISTS idx_verification_tokens_expiry
ON email_verification_tokens(expires_at);

CREATE TABLE IF NOT EXISTS wallets (
user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
balance_kobo BIGINT NOT NULL DEFAULT 0 CHECK (balance_kobo >= 0),
currency TEXT NOT NULL DEFAULT 'NGN' CHECK (currency = 'NGN'),
updated_at TEXT NOT NULL DEFAULT
(TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE IF NOT EXISTS transactions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
reference TEXT NOT NULL UNIQUE,
type TEXT NOT NULL
CHECK (type IN ('deposit', 'withdrawal', 'investment', 'return', 'adjustment')),
direction TEXT NOT NULL CHECK (direction IN ('credit', 'debit')),
amount_kobo BIGINT NOT NULL CHECK (amount_kobo > 0),
status TEXT NOT NULL DEFAULT 'pending'
CHECK (status IN ('pending', 'completed', 'failed', 'reversed')),
description TEXT NOT NULL,
created_at TEXT NOT NULL DEFAULT
(TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX IF NOT EXISTS idx_transactions_user_created
ON transactions(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS wallet_ledger_entries (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
transaction_id BIGINT NOT NULL UNIQUE REFERENCES transactions(id),
user_id BIGINT NOT NULL REFERENCES users(id),
delta_kobo BIGINT NOT NULL,
balance_after_kobo BIGINT NOT NULL CHECK (balance_after_kobo >= 0),
created_at TEXT NOT NULL DEFAULT
(TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX IF NOT EXISTS idx_wallet_ledger_user_created
ON wallet_ledger_entries(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS paystack_payments (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
reference TEXT NOT NULL UNIQUE,
amount_kobo BIGINT NOT NULL CHECK (amount_kobo > 0),
status TEXT NOT NULL DEFAULT 'pending'
CHECK (status IN ('pending', 'completed', 'failed')),
created_at TEXT NOT NULL DEFAULT
(TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
updated_at TEXT NOT NULL DEFAULT
(TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC',
'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX IF NOT EXISTS idx_paystack_payments_user
ON paystack_payments(user_id, created_at DESC);

